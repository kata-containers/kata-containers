# Guest SELinux triage for the k8s bats runner: after a failed run, save the
# guest denials it logged, and re-run the failed cases with the guest
# permissive on the debug handler.
#

# Only the NVIDIA runtime-rs handlers boot the guest with SELinux.
guest_selinux_enabled() {
	[[ "${KATA_HYPERVISOR:-}" == qemu-nvidia-*-runtime-rs ]]
}

# Configuration directory of the handler the drop-ins below target.
nv_runtime_dir() {
	# A multi-install appends its suffix to the installation directory and to
	# every handler name alike, so follow MULTI_INSTALL_SUFFIX for both or the
	# drop-in lands where the pods under test never look.
	local install_suffix="${MULTI_INSTALL_SUFFIX:+-${MULTI_INSTALL_SUFFIX}}"
	local kata_config_base="/opt/kata${install_suffix}/share/defaults/kata-containers"

	# The kata-<shim>-debug RuntimeClass, when kata-deploy creates it, reads
	# its configuration from a directory of its own under custom-runtimes/.
	local runtime_dir="${kata_config_base}/custom-runtimes/kata-${KATA_HYPERVISOR}${install_suffix}-debug"
	if [[ ! -d "${runtime_dir}" ]]; then
		case "${KATA_HYPERVISOR}" in
			*-runtime-rs) kata_config_base="${kata_config_base}/runtime-rs" ;;
		esac
		runtime_dir="${kata_config_base}/runtimes/${KATA_HYPERVISOR}"
	fi
	echo "${runtime_dir}"
}

# The kernel_params the handler boots with. A drop-in replaces the value
# instead of appending to it, so the last drop-in that sets it wins, and the
# base configuration applies when none does. $2 names a drop-in to ignore.
nv_effective_kernel_params() {
	local runtime_dir="$1"
	local ignore="${2:-}"
	local params=""
	local file

	local runtime_config="${runtime_dir}/configuration-${KATA_HYPERVISOR}.toml"
	if [[ -f "${runtime_config}" ]]; then
		params=$(grep -E '^kernel_params\s*=' "${runtime_config}" | sed 's/^kernel_params\s*=\s*"\(.*\)"/\1/' || true)
	fi
	for file in "${runtime_dir}"/config.d/*.toml; do
		[[ -f "${file}" ]] && [[ "${file}" != "${ignore}" ]] || continue
		if grep -qE '^kernel_params\s*=' "${file}"; then
			params=$(grep -E '^kernel_params\s*=' "${file}" | sed 's/^kernel_params\s*=\s*"\(.*\)"/\1/')
		fi
	done
	echo "${params}"
}

TRIAGE_GUEST_PERMISSIVE_DROP_IN="95-triage-guest-permissive.toml"

# The triage re-run of a failed test boots the guest permissive on the debug
# handler, so the log shows every denial the test would hit, not only the
# first one that stopped it.
enable_triage_guest_permissive() {
	guest_selinux_enabled || return 0

	local runtime_dir
	runtime_dir="$(nv_runtime_dir)"
	if [[ "${runtime_dir}" != */custom-runtimes/*-debug ]]; then
		info "No debug handler configuration; triage keeps the guest enforcing"
		return 0
	fi

	local drop_in_file="${runtime_dir}/config.d/${TRIAGE_GUEST_PERMISSIVE_DROP_IN}"
	local new_params
	new_params="$(nv_effective_kernel_params "${runtime_dir}" "${drop_in_file}") enforcing=0"

	info "Triage boots the guest permissive: ${drop_in_file}"
	sudo mkdir -p "${runtime_dir}/config.d"
	sudo tee "${drop_in_file}" > /dev/null <<EOF
# Permissive guest for triage re-runs of failed tests
# Generated by guest_selinux_triage.sh, removed after the re-runs

[hypervisor.qemu]
kernel_params = "${new_params}"
EOF
}

disable_triage_guest_permissive() {
	guest_selinux_enabled || return 0
	sudo rm -f "$(nv_runtime_dir)/config.d/${TRIAGE_GUEST_PERMISSIVE_DROP_IN}"
}

# Save the guest SELinux denials logged since a run started, and summarise
# them in the job log. The enforcing run shows what failed the test, the
# permissive triage re-run everything else the test needs.
collect_guest_selinux_denials_since() {
	local label="$1"
	local since="$2"
	local report_dir="$3"

	guest_selinux_enabled || return 0

	local out="${report_dir}/guest-selinux-denials-${label}.log"
	sudo journalctl --since="${since}" --no-pager | grep -F 'avc:' | grep -F 'denied' \
		| sed 's/\\//g' > "${out}" || true
	if [[ ! -s "${out}" ]]; then
		rm -f "${out}"
		info "No guest SELinux denials during ${label}"
		return 0
	fi

	warn "$(wc -l < "${out}") guest SELinux denials during ${label}, saved as ${out##*/}"
	grep -oE 'denied +\{[^}]*\}.*' "${out}" \
		| sed -E 's/ pid=[0-9]+//; s/ ino=[0-9]+//' \
		| sort | uniq -c | sort -rn
}

# Wire the triage into run_kubernetes_bats_tests.
setup_guest_selinux_triage() {
	guest_selinux_enabled || return 0
	export K8S_BATS_AFTER_FAILURE="collect_guest_selinux_denials_since"
	export K8S_BATS_BEFORE_TRIAGE="enable_triage_guest_permissive"
	export K8S_BATS_AFTER_TRIAGE="disable_triage_guest_permissive"
}
