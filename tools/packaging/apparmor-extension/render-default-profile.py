"""Render only the pinned containerd template, without host policy discovery."""

from pathlib import Path
import sys


def render() -> str:
    template = (Path(__file__).parent / "upstream/containerd-v2.2.1.template").read_text(
        encoding="utf-8"
    )
    # These are deliberately fixed substitutions, not containerd's loadData():
    # Imports=[], InnerImports=[], DaemonProfile=unconfined, RootlessKit="".
    for block in (
        "{{range $value := .Imports}}\n{{$value}}\n{{end}}",
        "{{range $value := .InnerImports}}\n  {{$value}}\n{{end}}",
        "{{if .RootlessKit}}\n  # https://github.com/containerd/nerdctl/issues/2730\n"
        "  signal (receive) peer={{.RootlessKit}},\n{{end}}",
    ):
        if template.count(block) != 1:
            raise ValueError("pinned upstream template changed; review the renderer")
        template = template.replace(block, "")
    template = template.replace("{{.Name}}", "cri-containerd.apparmor.d")
    template = template.replace("{{.DaemonProfile}}", "unconfined")
    if "{{" in template or "}}" in template:
        raise ValueError("unrendered upstream template action")
    return """# Copyright The docker Authors.
# Copyright The Moby Authors.
# Copyright The containerd Authors.
# Copyright (c) 2026 Kata Containers contributors
# SPDX-License-Identifier: Apache-2.0
#
# Derived from containerd v2.2.1 contrib/apparmor/template.go.
# See metadata/default-profile-source.txt and metadata/LICENSE.containerd.
# Generated by render-default-profile.py with fixed inputs; do not edit.
# This is the upstream baseline, not a complete container escape defense.

@{PROC}=/proc/
""" + template


if __name__ == "__main__":
    sys.stdout.buffer.write(render().encode("utf-8"))
